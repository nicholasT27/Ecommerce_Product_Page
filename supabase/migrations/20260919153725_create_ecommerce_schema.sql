create or replace function public.checkout(
  customer_name text,
  customer_email text,
  delivery_address text,
  delivery_city text,
  delivery_postal_code text
) returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  new_order_id bigint;
  new_order_number text;
  order_subtotal integer;
  order_shipping integer;
begin
  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;

  if coalesce(trim(customer_name), '') = ''
    or coalesce(trim(customer_email), '') = ''
    or coalesce(trim(delivery_address), '') = ''
    or coalesce(trim(delivery_city), '') = ''
    or coalesce(trim(delivery_postal_code), '') = '' then
    raise exception 'Please complete every checkout field.';
  end if;

  -- Lock the product rows while validating and reserving stock so two
  -- simultaneous checkouts cannot oversell the same inventory.
  perform 1
  from public.products as product
  join public.cart_items as cart_item on cart_item.product_id = product.id
  where cart_item.user_id = current_user_id
  for update of product;

  if not exists (select 1 from public.cart_items where user_id = current_user_id) then
    raise exception 'Your cart is empty.';
  end if;

  if exists (
    select 1 from public.cart_items
    join public.products on public.products.id = public.cart_items.product_id
    where public.cart_items.user_id = current_user_id
      and public.cart_items.quantity > public.products.stock
  ) then
    raise exception 'One or more products no longer have enough stock.';
  end if;

  select sum(public.products.price_cents * public.cart_items.quantity)::integer
  into order_subtotal
  from public.cart_items
  join public.products on public.products.id = public.cart_items.product_id
  where public.cart_items.user_id = current_user_id;

  order_shipping := case when order_subtotal >= 10000 then 0 else 800 end;
  new_order_number := 'SNK-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));

  insert into public.orders (
    order_number, user_id, customer_name, email, address, city, postal_code,
    subtotal_cents, shipping_cents, status
  ) values (
    new_order_number, current_user_id, trim(customer_name), trim(customer_email),
    trim(delivery_address), trim(delivery_city), trim(delivery_postal_code),
    order_subtotal, order_shipping, 'confirmed'
  ) returning id into new_order_id;

  insert into public.order_items (order_id, product_id, product_name, unit_price_cents, quantity)
  select new_order_id, public.products.id, public.products.name,
    public.products.price_cents, public.cart_items.quantity
  from public.cart_items
  join public.products on public.products.id = public.cart_items.product_id
  where public.cart_items.user_id = current_user_id;

  update public.products
  set stock = public.products.stock - public.cart_items.quantity,
      updated_at = now()
  from public.cart_items
  where public.cart_items.user_id = current_user_id
    and public.products.id = public.cart_items.product_id;

  delete from public.cart_items where user_id = current_user_id;
  return new_order_number;
end;
$$;

revoke all on function public.checkout(text, text, text, text, text) from public, anon;
grant execute on function public.checkout(text, text, text, text, text) to authenticated;
